// Optional: Playwright + the running Vite server; no enrollment API is used.
const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs/promises')
const { chromium } = require(process.env.MESHSTRATA_PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.MESHSTRATA_PREVIEW_URL || 'http://127.0.0.1:5173'
const output = path.resolve(process.env.MESHSTRATA_BROWSER_OUTPUT || '.local/browser-check/enrollment')
;(async () => {
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({ headless: true, ...(process.env.MESHSTRATA_CHROMIUM ? { executablePath: process.env.MESHSTRATA_CHROMIUM } : {}), args: ['--no-sandbox'] })
  const errors = [], api = []
  try {
    const context = await browser.newContext({ permissions: ['clipboard-read', 'clipboard-write'], viewport: { width: 1440, height: 1000 } })
    const page = await context.newPage()
    await page.clock.install()
    page.on('pageerror', e => errors.push(e.message))
    page.on('request', r => { if (/\/(api(?:\/|$)|healthz|readyz)/.test(new URL(r.url()).pathname)) api.push(r.url()) })
    page.on('dialog', d => d.accept())
    const click = name => page.getByRole('button', { name, exact: true }).click()
    let documentId = 0
    async function start(name, mode = 'direct') {
      await page.goto(`${base}/?enrollment-check=${++documentId}#/nodes/new`, { waitUntil: 'networkidle' })
      await page.getByLabel('Node name', { exact: true }).fill(name)
      if (mode === 'reverse') await page.getByRole('radio', { name: 'Reverse Tunnel', exact: true }).check()
      else await page.getByLabel('Proxy access address', { exact: true }).fill('node.example.invalid')
      await click('Continue')
      await page.getByRole('heading', { name: 'Run one command on your host', exact: true }).waitFor()
      await click('Generate install command')
    }
    const commandField = () => page.getByLabel('Installation command', { exact: true })
    await start("Browser's node")
    const first = await commandField().inputValue()
    assert.ok(first.includes('--advertise-address'))
    assert.ok(first.includes("Browser'\\''s node"), 'shell arguments quote apostrophes')
    assert.ok(first.split('\n').every(line => line.startsWith('# ')), 'copied demo never executes')
    await click('Regenerate command')
    assert.notEqual(await commandField().inputValue(), first)
    const regenerated = await commandField().inputValue()
    await page.screenshot({ path: path.join(output, 'install-desktop.png'), fullPage: true })
    await click('Copy command')
    await page.getByRole('heading', { name: 'Waiting for node', exact: true }).waitFor()
    assert.equal(await page.evaluate(() => navigator.clipboard.readText()), regenerated)
    await page.getByRole('heading', { name: 'Node online · simulated', exact: true }).waitFor()
    await page.clock.fastForward(16 * 60000)
    await click('Open Node Settings')
    await page.waitForURL(/\/nodes\/enrolled-/)
    assert.ok(!(await page.evaluate(() => localStorage.getItem('meshstrata.demo.v1'))).includes('DEMO-NOT-A-CREDENTIAL'))

    await page.setViewportSize({ width: 390, height: 844 })
    await start('Failure and retry')
    await page.locator('.demo-options summary').click()
    await page.getByLabel('Simulation outcome', { exact: true }).selectOption('failure')
    await click('Copy command')
    await page.getByText('Simulated identity mismatch.', { exact: false }).waitFor()
    assert.equal(await page.locator('.verification .success').count(), 1)
    await page.locator('.demo-options summary').click()
    await page.getByLabel('Simulation outcome', { exact: true }).selectOption('success')
    await click('Retry connection · demo')
    await page.getByRole('heading', { name: 'Node online · simulated', exact: true }).waitFor()
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2))

    await start('Reverse command', 'reverse')
    const reverse = await commandField().inputValue()
    assert.ok(reverse.includes('--connection-mode reverse'))
    assert.ok(reverse.includes('--relay-node-id'))
    assert.ok(!reverse.includes('--advertise-address'))
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2))
    await page.locator('h1').click()
    await page.evaluate(() => scrollTo(0, 0))
    await page.screenshot({ path: path.join(output, 'install-mobile.png'), fullPage: true })
    await click('Copy command')
    await click('Stop waiting')
    await page.waitForTimeout(3700)
    assert.equal(await page.getByRole('heading', { name: 'Node online · simulated', exact: true }).count(), 0)

    await start('Saved command draft')
    await click('Save Draft')
    await page.reload({ waitUntil: 'networkidle' })
    assert.equal(await commandField().count(), 0, 'refresh restores metadata, not a credential')
    await click('Generate install command')
    await page.clock.fastForward(16 * 60000)
    await commandField().waitFor({ state: 'detached' })
    assert.equal(await commandField().count(), 0, 'expired command is removed while the page stays open')
    await page.getByText('Command expired. Generate a new install command.', { exact: true }).waitFor()
    await page.clock.resume()
    await click('Generate install command')
    await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: () => Promise.reject(Error('denied')) } }))
    await click('Copy command')
    await page.getByText('Clipboard unavailable.', { exact: false }).waitFor()
    await click('Select command')
    assert.ok(await commandField().evaluate(e => e.selectionEnd > e.selectionStart))
    await page.getByRole('button', { name: /I have copied it manually/ }).click()
    await page.getByRole('heading', { name: 'Node online · simulated', exact: true }).waitFor()
    const unsafePreview = await page.evaluate(async () => {
      const { enrollmentCommand } = await import('/src/features/nodes/enrollment-command.ts')
      return enrollmentCommand({ name: "quoted'\n$(false)", form: { mode: 'direct', address: 'node.example.invalid', location: '' }, controller: 'https://controller.example.invalid', token: 'DEMO', relayNodeId: 'relay' })
    })
    assert.equal(unsafePreview.split('\n').length, 2)
    assert.ok(unsafePreview.split('\n').every(line => line.startsWith('# ')))
    assert.deepEqual(errors, [])
    assert.deepEqual(api, [])
    await fs.writeFile(path.join(output, 'result.json'), JSON.stringify({ flows: ['direct-copy-wait-finish', 'failure-retry', 'reverse-command', 'cancel', 'draft-refresh', 'live-expiry', 'clipboard-fallback', 'shell-argument-escaping'], errors, api }, null, 2))
    console.log('Enrollment browser checks passed: copy/wait/finish, failure/retry, Reverse, cancel, refresh, expiry, clipboard fallback, shell escaping and 390px layout. No business API requests.')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
