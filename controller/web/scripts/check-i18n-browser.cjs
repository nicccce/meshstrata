// Optional browser acceptance: isolated contexts against the already-running local Vite.
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { chromium } = require(process.env.MESHSTRATA_PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.MESHSTRATA_PREVIEW_URL || 'http://127.0.0.1:5173'
const output = path.resolve(process.env.MESHSTRATA_BROWSER_OUTPUT || '.local/browser-check/i18n')
const pages = ['/overview','/nodes','/nodes/new','/nodes/hk','/routes','/routes/new','/routes/direct','/routes/direct/edit','/client-config/subscriptions','/client-config/subscriptions/new','/client-config/subscriptions/sub-active','/client-config/subscriptions/sub-active/edit','/client-config/rule-profiles','/client-config/rule-profiles/new','/client-config/rule-profiles/default/edit','/activity','/activity/releases/release-failed','/settings','/login']
;(async () => {
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({ headless: true, ...(process.env.MESHSTRATA_CHROMIUM ? { executablePath: process.env.MESHSTRATA_CHROMIUM } : {}), args: ['--no-sandbox'] })
  const errors = [], warnings = [], api = [], overflows = [], visited = [], results = []
  let page
  try {
    const context = await browser.newContext({ locale: 'zh-TW', permissions: ['clipboard-read','clipboard-write'], viewport: { width: 1440, height: 1000 } })
    page = await context.newPage()
    // HMR may append timestamps. Import the exact module already used by the app,
    // so inspection never creates a second workspace/router in this test context.
    await page.addInitScript(() => { window.__meshstrataModule = async pathname => {
      const url = performance.getEntriesByType('resource').map(entry => entry.name).findLast(url => new URL(url).pathname === pathname)
      if (!url) throw Error(`App module not loaded: ${pathname}`)
      return import(url)
    } })
    page.setDefaultTimeout(15000)
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); if (message.type() === 'warning' && message.text().includes('[intlify]')) warnings.push(message.text()) })
    page.on('request', request => { if (/\/(api(?:\/|$)|healthz|readyz)/.test(new URL(request.url()).pathname)) api.push(request.url()) })
    page.on('dialog', dialog => dialog.accept())
    let sequence = 0
    const click = name => page.getByRole('button', { name, exact: true }).click()
    const lang = () => page.locator('html').getAttribute('lang')
    const stored = () => page.evaluate(async () => { const { workspace } = await window.__meshstrataModule('/src/demo/workspace.ts'); return JSON.parse(JSON.stringify(workspace)) })
    const locale = async value => page.evaluate(async value => { const { commands } = await window.__meshstrataModule('/src/demo/workspace.ts'); commands.updateSettings({ locale: value }) }, value)
    async function checkViewport(route) {
      const size = await page.evaluate(() => ({ document: document.documentElement.scrollWidth, viewport: innerWidth }))
      if (size.document > size.viewport + 2) overflows.push({ route, ...size, elements: await page.evaluate(() => [...document.querySelectorAll('main *, .n-modal *, .n-drawer *')].filter(element => element.getBoundingClientRect().right > innerWidth + 2).slice(0,10).map(element => ({ tag: element.tagName, class: element.className, right: Math.round(element.getBoundingClientRect().right) }))) })
    }
    async function go(route) {
      await page.goto(`${base}/?i18n-check=${++sequence}#${route}`, { waitUntil: 'networkidle' })
      await page.locator('h1, h2').first().waitFor()
      const title = await page.title()
      assert.ok(!title.includes('features.') && !title.includes('undefined'), route)
      const body = await page.locator('body').innerText()
      assert.ok(!/features\.[\w-]+\.[A-Za-z]/.test(body), `${route}: no missing key text`)
      assert.equal(title, await page.evaluate(async () => { const { router } = await window.__meshstrataModule('/src/app/router.ts'); const { i18n } = await window.__meshstrataModule('/src/i18n.ts'); return `${i18n.global.t(router.currentRoute.value.meta.titleKey ?? 'common.notFound')} · Meshstrata` }))
      await checkViewport(route)
      if ((visited.length + 1) % 20 === 0) console.log(`Visited ${visited.length + 1} pages`)
      visited.push({ route, lang: await lang(), title, width: (await page.viewportSize()).width })
    }
    async function chooseLanguage(label) {
      await page.locator('.n-select[aria-labelledby="locale-label"]').click()
      await page.getByText(label, { exact: true }).last().click()
    }
    await go('/settings')
    assert.equal(await lang(), 'zh-CN', 'Chinese browser defaults to Simplified Chinese')
    assert.equal(await page.title(), '设置 · Meshstrata')
    assert.equal((await stored()).settings.locale, undefined, 'browser default is not an explicit choice')
    await page.evaluate(async () => {
      const { commands, workspace } = await window.__meshstrataModule('/src/demo/workspace.ts')
      commands.upsert('nodes', { ...JSON.parse(JSON.stringify(workspace.nodes[1])), name: '用户名称 Keep English HK-01' })
      commands.saveDraft({ id: 'locale-preserve', feature: 'test', name: '草稿 Draft unchanged', nodeIds: ['hk'], routeIds: [], updatedAt: '' })
    })
    const before = await stored(), beforeURL = page.url()
    await chooseLanguage('English')
    assert.equal(page.url(), beforeURL, 'switch does not navigate')
    assert.equal(await lang(), 'en')
    assert.equal(await page.title(), 'Settings · Meshstrata', 'title changes without navigation')
    const after = await stored()
    assert.deepEqual({ ...after, settings: { ...after.settings, locale: undefined } }, { ...before, settings: { ...before.settings, locale: undefined } }, 'language preserves records, names, events and drafts')
    await page.reload({ waitUntil: 'networkidle' })
    assert.equal(await lang(), 'en', 'saved English overrides Chinese browser after refresh')
    await page.locator('.demo-controls summary').click()
    await click('Reset Demo')
    assert.equal((await stored()).settings.locale, 'en', 'Reset Demo preserves explicit English')
    await chooseLanguage('简体中文')
    assert.equal(await page.title(), '设置 · Meshstrata')
    await page.reload({ waitUntil: 'networkidle' })
    assert.equal(await lang(), 'zh-CN')
    await page.locator('.demo-controls summary').click()
    await click('重置演示')
    assert.equal(await lang(), 'zh-CN')
    assert.equal((await stored()).settings.locale, 'zh-CN', 'Reset Demo preserves explicit language')
    await page.reload({ waitUntil: 'networkidle' })
    assert.equal(await lang(), 'zh-CN')
    console.log('Locale selection and persistence checks complete')
    results.push('Browser default zh-TW, immediate bilingual UI switch/title/lang, refresh, stored preference, record/draft preservation and Reset Demo')
    for (const value of ['zh','zh-HK','zh_Hant','unknown-language',42,false,{ language:'zh-CN' }]) {
      await locale(value); await page.reload({ waitUntil: 'networkidle' })
      assert.equal(await lang(), typeof value === 'string' && value.startsWith('zh') ? 'zh-CN' : 'en')
    }
    results.push('Persisted Chinese variants normalize to zh-CN; unknown stored locale falls back to English')
    for (const language of ['en','zh-CN']) {
      await locale(language)
      for (const route of pages) {
        await go(route)
        if (route === '/routes') assert.ok((await page.locator('.n-pagination').innerText()).includes(language === 'zh-CN' ? '/ 页' : '/ page'), 'Naive pagination follows UI language')
      }
    }
    await go('/client-config/subscriptions/new')
    await page.locator('.n-date-picker .n-input').click()
    await page.locator('.n-date-panel').waitFor()
    assert.ok((await page.locator('.n-date-panel').innerText()).includes('此刻'), 'Naive date picker Chinese built-ins')
    await page.screenshot({ path: path.join(output,'zh-date-picker-desktop.png'), fullPage: true })
    await page.keyboard.press('Escape')
    await locale('en')
    await go('/client-config/subscriptions/new')
    await page.locator('.n-date-picker .n-input').click()
    assert.ok((await page.locator('.n-date-panel').innerText()).includes('Now'), 'Naive date picker English built-ins')
    await page.keyboard.press('Escape')
    await go('/client-config/subscriptions/sub-active?tab=usage')
    const englishDate = await page.evaluate(async () => {
      const { workspace, commands } = await window.__meshstrataModule('/src/demo/workspace.ts')
      commands.upsert('usage', { ...JSON.parse(JSON.stringify(workspace.usage[0])), bytes: 1234567, metric: 'cumulative_bytes' })
      return new Intl.DateTimeFormat('en', { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(workspace.usage[0].coverageStart))
    })
    assert.ok((await page.locator('body').innerText()).includes(englishDate), 'English dates despite Chinese browser')
    assert.ok((await page.locator('body').innerText()).includes('1,234,567'), 'Intl grouped numbers')
    await locale('zh-CN')
    console.log('Desktop bilingual routes and date-picker checks complete')
    results.push('All 19 routes in both languages; Naive UI date picker switches Chinese/English')
    const tabs = ['/nodes/hk?tab=protocols','/nodes/hk?tab=dns','/nodes/reverse?tab=connectivity','/nodes/hk?tab=routes','/routes/direct?tab=measurements','/routes/direct?tab=resources','/routes/failed-route?tab=history','/client-config/subscriptions/sub-active?tab=entries','/client-config/subscriptions/sub-active?tab=config','/client-config/subscriptions/sub-active?tab=usage','/activity?tab=releases','/activity?tab=logs']
    for (const route of tabs) await go(route)
    for (const section of ['ports','relay','location','certificates','client','logs','admin']) await go(`/settings?section=${section}`)
    for (const route of ['/nodes/missing','/routes/missing','/client-config/subscriptions/missing','/client-config/rule-profiles/missing/edit','/activity/releases/missing','/unknown']) await go(route)
    // Date/number output must follow the selected UI language, not navigator.language.
    await go('/client-config/subscriptions/sub-active?tab=usage')
    const format = await page.evaluate(async () => {
      const { i18n } = await window.__meshstrataModule('/src/i18n.ts')
      const { workspace } = await window.__meshstrataModule('/src/demo/workspace.ts')
      return { date: new Intl.DateTimeFormat(i18n.global.locale.value, { dateStyle:'medium',timeStyle:'short' }).format(new Date(workspace.usage[0].coverageStart)), locale: navigator.language }
    })
    assert.equal(format.locale, 'zh-TW')
    assert.ok((await page.locator('body').innerText()).includes(format.date))
    await go('/routes/custom?panel=egress')
    await page.locator('.n-drawer').waitFor()
    assert.ok((await page.locator('.n-drawer').innerText()).includes('出口'))
    await page.screenshot({ path:path.join(output,'zh-egress-drawer-desktop.png'),fullPage:true })
    await page.keyboard.press('Escape')
    await go('/client-config/subscriptions/sub-active')
    await click('重置下载链接')
    await page.getByText('重置下载链接？',{exact:true}).waitFor()
    await page.screenshot({ path:path.join(output,'zh-confirm-desktop.png'),fullPage:true })
    await click('取消')
    for (const scenario of ['empty','error','stale','offline','partial']) {
      await page.evaluate(async scenario => { const { commands } = await window.__meshstrataModule('/src/demo/workspace.ts'); commands.reset(scenario) },scenario)
      for (const route of ['/overview','/nodes','/routes','/client-config/subscriptions','/activity']) await go(route)
    }
    await page.evaluate(async () => { const { commands } = await window.__meshstrataModule('/src/demo/workspace.ts'); commands.reset() })
    results.push('Chinese tabs, 8 settings sections, missing objects, dates, drawers, confirmations and all five alternate demo scenarios')
    await page.setViewportSize({ width:390,height:844 })
    for (const route of pages) await go(route)
    await go('/overview')
    await page.screenshot({ path:path.join(output,'zh-overview-mobile.png'),fullPage:true })
    await page.getByRole('button',{name:'打开导航',exact:true}).click()
    await page.locator('.n-drawer').getByRole('navigation',{name:'主导航',exact:true}).waitFor()
    await checkViewport('mobile-navigation')
    await page.screenshot({ path:path.join(output,'zh-navigation-mobile.png'),fullPage:true })
    await page.keyboard.press('Escape')
    await go('/nodes/new')
    await click('继续')
    await page.getByText('请输入节点名称。',{exact:true}).first().waitFor()
    await page.getByLabel('节点名称',{exact:true}).fill('中文节点 Browser Keep')
    await page.getByLabel('代理访问地址',{exact:true}).fill('node.example.invalid')
    await click('继续')
    await click('生成安装命令')
    const command = await page.getByLabel('安装命令',{exact:true}).inputValue()
    assert.ok(command.includes('--advertise-address') && command.split('\n').every(line=>line.startsWith('# ')))
    await checkViewport('mobile-command')
    await page.screenshot({ path:path.join(output,'zh-command-mobile.png'),fullPage:true })
    await click('复制命令')
    await page.getByRole('heading',{name:'等待节点',exact:true}).waitFor()
    await page.getByRole('heading',{name:'节点已上线 · 模拟',exact:true}).waitFor()
    assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),command)
    await checkViewport('mobile-online')
    await page.screenshot({ path:path.join(output,'zh-online-mobile.png'),fullPage:true })
    await click('打开节点设置')
    await page.waitForURL(/\/nodes\/enrolled-/)
    results.push('390px: all 19 pages, mobile navigation, translated validation, full commented command, clipboard → waiting → four progress items → simulated online → node settings')
    await go('/client-config/subscriptions/sub-active')
    await click('重置下载链接')
    await page.getByText('重置下载链接？',{exact:true}).waitFor()
    await checkViewport('mobile-confirm')
    await page.screenshot({ path:path.join(output,'zh-confirm-mobile.png'),fullPage:true })
    await click('取消')
    await go('/routes/custom?panel=egress')
    await page.locator('.n-drawer').waitFor()
    await checkViewport('mobile-egress-drawer')
    await page.screenshot({ path:path.join(output,'zh-egress-drawer-mobile.png'),fullPage:true })
    await page.keyboard.press('Escape')
    results.push('390px confirmation and egress drawer')
    await context.close()
    // Separate browser contexts establish default/fallback without touching the user browser.
    for (const [language,expected] of [['en-US','en'],['fr-FR','en'],['zh-CN','zh-CN']]) {
      const other = await browser.newContext({locale:language})
      const otherPage = await other.newPage()
      await otherPage.goto(`${base}/#/settings`,{waitUntil:'networkidle'})
      assert.equal(await otherPage.locator('html').getAttribute('lang'),expected)
      await other.close()
    }
    results.push('Fresh en-US, fr-FR and zh-CN contexts use correct defaults')
    assert.deepEqual(errors,[],'runtime errors')
    assert.deepEqual(warnings,[],'missing translation / interpolation warnings')
    assert.deepEqual(api,[],'no automatic API requests')
    assert.deepEqual(overflows,[],'viewport overflow')
    await fs.writeFile(path.join(output,'results.json'),JSON.stringify({results,visited,errors,warnings,api,overflows},null,2))
    await fs.rm(path.join(output,'failure.json'),{force:true})
    await fs.rm(path.join(output,'failure.png'),{force:true})
    console.log(`i18n browser checks passed: ${visited.length} route/scenario/viewport visits; ${results.length} behavior groups. Results: ${output}`)
  } catch(error) {
    if(page&&!page.isClosed())await page.screenshot({path:path.join(output,'failure.png'),fullPage:true}).catch(()=>{})
    await fs.writeFile(path.join(output,'failure.json'),JSON.stringify({error:error.stack,results,visited,errors,warnings,api,overflows},null,2))
    throw error
  } finally { await browser.close() }
})().catch(error=>{console.error(error);process.exitCode=1})
