const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs/promises')
const { chromium } = require(process.env.MESHSTRATA_PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.MESHSTRATA_PREVIEW_URL || 'http://127.0.0.1:5173'
const output = path.resolve('.local/browser-check/regulation')
;(async () => {
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({ headless: true, ...(process.env.MESHSTRATA_CHROMIUM ? { executablePath: process.env.MESHSTRATA_CHROMIUM } : {}), args: ['--no-sandbox'] })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    const page = await context.newPage()
    const errors = [], api = [], warnings = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('console', m => { if (m.type() === 'warning' && m.text().includes('[intlify]')) warnings.push(m.text()) })
    page.on('request', r => { if (/\/(api(?:\/|$)|healthz|readyz)/.test(new URL(r.url()).pathname)) api.push(r.url()) })
    page.on('dialog', d => d.accept())
    let documentId = 0
    const go = async route => { await page.goto(`${base}/?regulation-check=${++documentId}#${route}`, { waitUntil: 'networkidle' }); await page.locator('h1').first().waitFor() }
    const click = name => page.getByRole('button', { name, exact: true }).click()
    const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('meshstrata.demo.v1')))
    await go('/overview')
    await page.evaluate(async () => { const { commands } = await import('/src/demo/workspace.ts'); commands.updateSettings({ environment: 'strong_regulation' }) })
    await go('/routes/new?exitNodeId=hk')
    const preferences = page.locator('.recommendation-preferences')
    assert.equal(await preferences.getAttribute('open'), null)
    assert.ok((await page.locator('.regulation-summary').innerText()).includes('Strong regulation'))
    assert.ok(!(await page.locator('body').innerText()).match(/Access environment|Mainland China/))
    await preferences.locator('summary').click()
    await preferences.locator('.n-select').click()
    await page.getByText('Weak regulation', { exact: true }).last().click()
    await click('Next')
    await click('Recommend routes')
    await page.locator('.candidate').first().getByRole('checkbox').click()
    await click('Save draft')
    await page.waitForURL(/draftId=/)
    const weak = await stored()
    const weakDraft = weak.drafts.find(d => d.feature === 'route-editor')
    assert.equal(weakDraft.data.route.environment, 'weak_regulation')
    assert.equal(weak.settings.environment, 'strong_regulation', 'draft override must not change settings')
    assert.equal(weak.listeners.find(l => l.id === weakDraft.data.route.selectedPaths[0].revision.entryListenerId).protocol, 'ss2022')

    await go('/routes/new?exitNodeId=hk&step=paths')
    await click('Recommend routes')
    await page.locator('.candidate').first().getByRole('checkbox').click()
    await click('Save draft')
    await page.waitForURL(/draftId=/)
    const strong = await stored()
    const strongDraft = strong.drafts.find(d => d.feature === 'route-editor' && d.id !== weakDraft.id)
    assert.equal(strongDraft.data.route.environment, 'strong_regulation')
    assert.equal(strong.listeners.find(l => l.id === strongDraft.data.route.selectedPaths[0].revision.entryListenerId).protocol, 'vless')

    await go('/settings?section=general')
    assert.ok((await page.locator('body').innerText()).includes('Default client network regulation'))
    assert.ok(!(await page.locator('body').innerText()).includes('Access environment'))
    await go('/nodes/new')
    assert.deepEqual(await page.locator('#enroll-environment option').allTextContents(), ['Strong regulation', 'Weak regulation'])
    await page.evaluate(() => {
      const raw = localStorage.getItem('meshstrata.demo.v1')
      localStorage.setItem('meshstrata.demo.v1', raw.replaceAll('strong_regulation', 'mainland_china').replaceAll('weak_regulation', 'outside_mainland_china'))
    })
    await go(`/routes/new?draftId=${encodeURIComponent(weakDraft.id)}&step=exit`)
    assert.ok((await page.locator('.regulation-summary').innerText()).includes('Weak regulation'))
    const migrated = await page.evaluate(async () => { const { workspace } = await import('/src/demo/workspace.ts'); return JSON.parse(JSON.stringify(workspace)) })
    assert.equal(migrated.settings.environment, 'strong_regulation')
    assert.equal(migrated.drafts.find(d => d.id === weakDraft.id).data.route.environment, 'weak_regulation')
    await go('/nodes?environment=mainland_china')
    assert.equal(await page.locator('#node-environment').inputValue(), 'strong_regulation')

    await go('/routes/new?exitNodeId=hk')
    await page.screenshot({ path: path.join(output, 'create-route-desktop.png'), fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.locator('h1').click()
    await page.evaluate(() => scrollTo(0, 0))
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2))
    await page.screenshot({ path: path.join(output, 'create-route-mobile.png'), fullPage: true })
    assert.deepEqual(errors, [])
    assert.deepEqual(api, [])
    assert.deepEqual(warnings, [])
    await fs.writeFile(path.join(output, 'result.json'), JSON.stringify({ checks: ['default inheritance', 'collapsed preferences', 'draft override', 'protocol suggestions', 'canonical labels', 'legacy draft migration', 'legacy filter link', '390px layout'], errors, api, warnings }, null, 2))
    console.log('Regulation browser checks passed: inherited defaults, optional override, strong/weak protocol suggestions, labels, legacy drafts/links and 390px layout. No API requests or runtime errors.')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
